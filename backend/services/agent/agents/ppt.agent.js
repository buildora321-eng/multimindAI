
import { getModel } from "../config/llmModels.js";
import { generatePpt } from "../utils/generatePpt.js";
import fs from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

export const pptAgent = async (state) => {
    try {
        const llm = await getModel("ppt");

        const prompt = `You are a professional presentation designer.

Return ONLY valid JSON.

Format:

{
    "title": "",
    "subtitle": "",
    "slides": [
        {
            "title": "",
            "points": [
                "",
                "",
                "",
                ""
            ]
        }
    ]
}

- Generate exactly 6 content slides.
- Each slide should have 4-6 concise bullet points.
- No markdown.
- No explanation.
- No code block.
- Return ONLY JSON.

Topic:

${state.prompt}`;

        const res = await llm.invoke(prompt);

        const rawContent = typeof res.content === "string"
            ? res.content
            : Array.isArray(res.content)
                ? res.content.map(item => item.text || "").join("")
                : "";

        const content = rawContent.trim()
            .replace(/^```json\s*/i, "")
            .replace(/^```\s*/i, "")
            .replace(/\s*```$/, "");

        const data = JSON.parse(content);

        // Validate presentation data
        if (
            !data.title ||
            !Array.isArray(data.slides) ||
            data.slides.length === 0
        ) {
            throw new Error("Invalid presentation data generated by AI");
        }

        // Generate the PowerPoint
        const ppt = await generatePpt(data);

        const buffer = await ppt.write({
            outputType: "nodebuffer"
        });

        // Create generated directory
       const generatedDir = path.resolve(__dirname, "../generated");

        await fs.mkdir(generatedDir, {
            recursive: true
        });

        // Save actual PPTX file
        const filename = `ppt-${Date.now()}-${Math.random()
            .toString(36)
            .slice(2, 8)}.pptx`;

        const filePath = path.join(generatedDir, filename);

        await fs.writeFile(filePath, buffer);

        console.log("PPT FILE SAVED:", filePath);

        const baseUrl = (
            process.env.PUBLIC_FILE_BASE_URL || "http://localhost:8000"
        ).replace(/\/+$/, "");

        return {
            ...state,

            aiResponse: `Presentation Generated Successfully!

**${data.title}**

Your presentation is ready to download.`,

            artifacts: [
                {
                    title: data.title,
                    name: filename,
                    type: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
                    url: `${baseUrl}/generated/${encodeURIComponent(filename)}`
                }
            ]
        };

    } catch (error) {
        console.error("PPT Agent Error:", error);

        return {
            ...state,
            aiResponse: "Failed to generate PPT. Please try again.",
            artifacts: []
        };
    }
};
